'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const [appPath,root,version]=process.argv.slice(2);
const {Vault}=require(path.resolve(appPath,'vault.js'));
const {PublicLibrary}=require(path.resolve(appPath,'library.js'));
const meta=JSON.parse(fs.readFileSync(path.join(appPath,'package.json'),'utf8'));
assert.equal(meta.version,version);assert.equal(meta.main,'main.js');
const fixture=JSON.parse(fs.readFileSync(path.join(root,'upgrade-fixture.json'),'utf8'));
assert.notEqual(version,fixture.oldVersion);
const vault=new Vault(path.join(root,'vault'));vault.unlock('fixture-update-password');
const book=vault.list().find(e=>e.id===fixture.id);
assert.equal(book.progress.position,1);assert.equal(book.progress.fraction,.25);
assert.ok(JSON.parse(vault.load(book.id).toString()).paragraphs.includes('虚构的升级验证内容'));vault.lock();
const library=new PublicLibrary(path.join(root,'public'));
const normal=library.list().find(e=>e.id===fixture.normalId);
assert.equal(normal.progress.position,2);assert.equal(normal.progress.fraction,.5);
assert.match(library.load(normal).toString(),/虚构的升级验证内容/);
const prefs=JSON.parse(fs.readFileSync(path.join(root,'preferences.json'),'utf8'));
assert.equal(prefs.name,'更新测试');assert.equal(prefs.readerTheme,'forest');
assert.ok(fs.readFileSync(path.join(appPath,'main.js'),'utf8').includes("id: 'check-update'"));
console.log('Verified production version, encrypted/public content, progress, preferences and update menu');
